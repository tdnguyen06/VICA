param(
    [string]$SourceRoot = (Join-Path $PSScriptRoot '..\..'),
    [string]$OutputRoot = $SourceRoot
)
$ErrorActionPreference = 'Stop'
$registry = Get-Content -Raw -LiteralPath (Join-Path $SourceRoot 'docs\api\provinces-v1.json') | ConvertFrom-Json
$sourcePath = Join-Path $SourceRoot $registry.sourceFile
if ((Get-FileHash -LiteralPath $sourcePath -Algorithm SHA256).Hash.ToLowerInvariant() -ne $registry.sourceSha256) {
    throw 'Source hash differs from the locked registry. Create a new dataset version instead.'
}
$geo = Get-Content -Raw -LiteralPath $sourcePath | ConvertFrom-Json
if ($registry.provinces.Count -ne 63 -or @($registry.provinces.id | Sort-Object -Unique).Count -ne 63 -or
    @($registry.provinces.slug | Sort-Object -Unique).Count -ne 63) { throw 'Registry IDs/slugs must be unique.' }
function Quote-Sql([string]$value) { return "'" + $value.Replace("'", "''") + "'" }
$sql = [Text.StringBuilder]::new()
[void]$sql.AppendLine('-- Generated by scripts/geo/Build-GeographicSeed.ps1. Do not edit applied migrations.')
[void]$sql.AppendLine('-- Dataset vica-demo-63-v1. Source and license are not yet verified. No geometry repair is applied.')
[void]$sql.AppendLine("INSERT INTO geographic_datasets VALUES ('vica-demo-63-v1', $(Quote-Sql $registry.sourceFile), $(Quote-Sql $registry.sourceSha256), $(Quote-Sql $registry.sourceCommit), 'UNVERIFIED', 'UNVERIFIED');")
foreach ($province in $registry.provinces) {
    $features = @($geo.features | Where-Object { -not $_.properties.is_sovereignty -and $_.properties.Name -ceq $province.sourceName })
    if ($features.Count -ne 1) { throw "Expected exactly one administrative feature for $($province.slug)" }
    if ($features[0].geometry.type -notin @('MultiPolygon', 'Polygon')) { throw 'Unsupported geometry type' }
    $geometry = $features[0].geometry | ConvertTo-Json -Depth 100 -Compress
    $values = "$($province.id), $(Quote-Sql $province.slug), $(Quote-Sql $province.name), $(Quote-Sql $province.adminUnit), 'vica-demo-63-v1', ST_Multi(ST_SetSRID(ST_GeomFromGeoJSON($(Quote-Sql $geometry)),4326))"
    [void]$sql.AppendLine("INSERT INTO provinces (id,slug,name,admin_unit,dataset_version,boundary) VALUES ($values);")
}
[void]$sql.AppendLine('ANALYZE provinces;')
foreach ($relative in @('backend\src\main\resources\db\migration', 'database\migrations')) {
    $directory = Join-Path $OutputRoot $relative
    New-Item -ItemType Directory -Path $directory -Force | Out-Null
    [IO.File]::WriteAllText((Join-Path $directory 'V5__seed_demo_province_boundaries.sql'), $sql.ToString(), [Text.UTF8Encoding]::new($false))
}
Write-Output 'Generated 63 province identities and boundaries; display-only features excluded.'
$frontendData = Join-Path $OutputRoot 'frontend\src\data'
New-Item -ItemType Directory -Path $frontendData -Force | Out-Null
Copy-Item -LiteralPath (Join-Path $SourceRoot 'docs\api\provinces-v1.json') -Destination (Join-Path $frontendData 'provinces-v1.json') -Force
