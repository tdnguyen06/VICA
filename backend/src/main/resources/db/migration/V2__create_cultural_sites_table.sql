-- ==========================================================
-- Vietnam Cultural Atlas - Cultural Sites & GIS Schema
-- PostGIS Spatial Column: geom geometry(Point, 4326)
-- ==========================================================

CREATE TABLE IF NOT EXISTS cultural_sites (
    id BIGSERIAL PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL UNIQUE,
    category VARCHAR(50) NOT NULL,
    category_label VARCHAR(100) NOT NULL,
    province VARCHAR(100) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    description TEXT NOT NULL,
    unesco_year INTEGER,
    historical_period VARCHAR(100),
    thumbnail_url VARCHAR(500),
    color VARCHAR(20) NOT NULL DEFAULT '#d97706',
    featured BOOLEAN NOT NULL DEFAULT FALSE,
    geom geometry(Point, 4326),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_cultural_sites_category ON cultural_sites(category);
CREATE INDEX IF NOT EXISTS idx_cultural_sites_province ON cultural_sites(province);
CREATE INDEX IF NOT EXISTS idx_cultural_sites_geom ON cultural_sites USING GIST(geom);

