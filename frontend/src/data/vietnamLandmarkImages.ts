export const DEFAULT_LANDMARK_IMAGE = {
  url: "https://upload.wikimedia.org/wikipedia/commons/2/2c/Hanoi_citadel.jpg",
  caption: "Hoàng thành Thăng Long - Di sản Văn hóa Cổ truyền Dân tộc Việt Nam"
};

export function getLandmarkImageData(provinceName: string): { url: string; caption: string; wikiTitle?: string } {
  if (!provinceName) return DEFAULT_LANDMARK_IMAGE;

  // 1. Direct match
  if (LANDMARK_IMAGES[provinceName]) return LANDMARK_IMAGES[provinceName];

  // 2. Normalized matching
  const clean = provinceName
    .toLowerCase()
    .normalize('NFC')
    .replace(/^(tỉnh|thành phố|tp\.|quần đảo|đảo|huyện đảo|huyện)\s+/i, '')
    .trim();

  // Fast-path for key maritime territories
  if (clean.includes('hoàng sa')) return LANDMARK_IMAGES['Quần đảo Hoàng Sa'];
  if (clean.includes('trường sa')) return LANDMARK_IMAGES['Quần đảo Trường Sa'];
  if (clean.includes('bạch long vĩ')) return LANDMARK_IMAGES['Đảo Bạch Long Vĩ'];
  if (clean.includes('côn đảo')) return LANDMARK_IMAGES['Côn Đảo'];
  if (clean.includes('phú quốc')) return LANDMARK_IMAGES['Phú Quốc'];
  if (clean.includes('lý sơn')) return LANDMARK_IMAGES['Lý Sơn'];

  for (const [key, val] of Object.entries(LANDMARK_IMAGES)) {
    const keyClean = key
      .toLowerCase()
      .normalize('NFC')
      .replace(/^(tỉnh|thành phố|tp\.|quần đảo|đảo|huyện đảo|huyện)\s+/i, '')
      .trim();
    if (clean === keyClean || clean.includes(keyClean) || keyClean.includes(clean)) {
      return val;
    }
  }

  // 3. Fallback for any other maritime query to Truong Sa instead of Hanoi Citadel
  const lower = provinceName.toLowerCase();
  if (lower.includes('đảo') || lower.includes('quần đảo')) {
    return LANDMARK_IMAGES['Quần đảo Trường Sa'];
  }

  return DEFAULT_LANDMARK_IMAGE;
}
