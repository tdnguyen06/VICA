export function getFallbackCultureEntries(slug: string, type: EntryType): CultureEntrySummary[] {
  const custom = COMPREHENSIVE_CULTURE_REGISTRY[slug];
  if (custom && custom.entries[type] && custom.entries[type].length > 0) {
    return custom.entries[type].map(e => ({
      id: e.id,
      slug: e.slug,
      provinceSlug: e.provinceSlug,
      type: e.type,
      category: e.category,
      name: e.name,
      summary: e.summary,
      verificationStatus: e.verificationStatus,
      coordinate: e.coordinate,
      thumbnailUrl: e.media?.find(m => m.mediaType === 'IMAGE')?.url || null,
      sourceCount: e.sources?.length || 1,
    }));
  }
  const overview = getFallbackCultureOverview(slug);
  return overview.highlights.filter(h => h.type === type);
}
